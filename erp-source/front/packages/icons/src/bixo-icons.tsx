export type IconName = keyof typeof IconMap;
export type IconSize = "large" | "medium" | "small" | "tiny" | number;
export type IconVariant = "outlined" | "contained";

export type BixoIconsProps = {
  variant?: IconVariant;
  className?: string;
  size?: IconSize;
  strokeWidth?: number;
  oneTone?: boolean;
  style?: React.CSSProperties;
};

export type BixoIconsPropsComponent = BixoIconsProps & {
  icon: IconName;
};

const BixoIcons: React.FC<BixoIconsPropsComponent> = ({
  icon,
  size = 20,
  variant = "outlined",
  className,
  strokeWidth = 1.5,
  oneTone = false,
  style,
}) => {
  const IconComponent = IconMap[icon];
  if (!IconComponent) {
    // console.warn(`Icon "${icon}" not found in IconMap.`);
    return null;
  }
  return (
    <IconComponent variant={variant} size={size} className={className} strokeWidth={strokeWidth} oneTone={oneTone} style={style} />
  );
};

export const sizeHelper = (size: BixoIconsProps["size"]) => {
  if (typeof size === "number") {
    return size;
  } else if (size === "large") {
    return 24;
  } else if (size === "small" || size === "tiny") {
    return 16;
  } else {
    return 20;
  }
};

export const strokeSizeHelper = (size: number) => {
  if (size === 36) {
    return 1;
  } else if (size >= 20) {
    return 1.5;
  } else if (size < 20) {
    return 1.75;
  }
};

export default BixoIcons;

